
from decimal import Decimal

from sqlalchemy import and_, func, or_, select
from sqlalchemy.orm import Session, selectinload

from app.models.category import Category
from app.models.product import Product
from app.models.product_variant import ProductVariant


def search_products(
    db: Session,
    *,
    keyword: str | None = None,
    color: str | None = None,
    category: str | None = None,
    min_price: Decimal | None = None,
    max_price: Decimal | None = None,
    available_only: bool = True,
    limit: int = 8,
) -> list[Product]:
    """
    Search active products using the existing database.

    This function only reads products. It does not add items to a cart
    or create orders.
    """

    # Load variants and categories with products to avoid repeated queries.
    statement = (
        select(Product)
        .where(Product.is_active.is_(True))
        .options(
            selectinload(Product.variants),
            selectinload(Product.categories),
        )
        .distinct()
    )

    # Search product name, description, slug, and category.
    if keyword:
        terms = [term.strip() for term in keyword.split() if term.strip()]

        for term in terms:
            pattern = f"%{term}%"

            statement = statement.where(
                or_(
                    Product.name.ilike(pattern),
                    Product.slug.ilike(pattern),
                    Product.description.ilike(pattern),
                    Product.categories.any(Category.name.ilike(pattern)),
                )
            )

    # Search variant color, such as black, blue, or white.
    if color:
        statement = statement.where(
            Product.variants.any(
                and_(
                    ProductVariant.is_active.is_(True),
                    ProductVariant.color.ilike(f"%{color}%"),
                )
            )
        )

    # Search by category name.
    if category:
        statement = statement.where(
            Product.categories.any(
                and_(
                    Category.is_active.is_(True),
                    Category.name.ilike(f"%{category}%"),
                )
            )
        )

    # Search products with a matching base or variant price.
    if min_price is not None or max_price is not None:
        effective_variant_price = func.coalesce(
            ProductVariant.price,
            Product.price,
        )

        price_conditions = []

        if min_price is not None:
            price_conditions.append(
                effective_variant_price >= min_price
            )

        if max_price is not None:
            price_conditions.append(
                effective_variant_price <= max_price
            )

        matching_variant = and_(
            ProductVariant.is_active.is_(True),
            *price_conditions,
        )

        # A product without active variants uses its own price.
        no_active_variants = ~Product.variants.any(
            ProductVariant.is_active.is_(True)
        )

        base_price_conditions = []

        if min_price is not None:
            base_price_conditions.append(Product.price >= min_price)

        if max_price is not None:
            base_price_conditions.append(Product.price <= max_price)

        statement = statement.where(
            or_(
                Product.variants.any(matching_variant),
                and_(
                    no_active_variants,
                    *base_price_conditions,
                ),
            )
        )

    # Include products that have available stock at product or variant level.
    if available_only:
        statement = statement.where(
            or_(
                Product.stock > 0,
                Product.variants.any(
                    and_(
                        ProductVariant.is_active.is_(True),
                        ProductVariant.stock > 0,
                    )
                ),
            )
        )

    statement = statement.order_by(Product.id.desc()).limit(
        max(1, min(limit, 20))
    )

    products = db.scalars(statement).unique().all()

    return list(products)


def build_shopping_product_response(product: Product) -> dict:
    """
    Convert a Product ORM object into data for the shopping chat API.
    Prices are taken from the database, not generated by the AI.
    """

    active_variants = [
        variant
        for variant in product.variants
        if variant.is_active
    ]

    variants = [
        {
            "id": variant.id,
            "sku": variant.sku,
            "size": variant.size,
            "color": variant.color,
            "price": (
                variant.price
                if variant.price is not None
                else product.price
            ),
            "stock": variant.stock,
        }
        for variant in active_variants
    ]

    return {
        "id": product.id,
        "name": product.name,
        "slug": product.slug,
        "description": product.description,
        "image": product.image,
        "price": product.price,
        "stock": product.stock,
        "variants": variants,
    }
